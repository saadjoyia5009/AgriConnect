  String tDynamic(String value) {
    final trimmed = value.trim();
    if (trimmed.isEmpty) return value;

    if (trimmed.startsWith('/')) {
      return '/${tDynamic(trimmed.substring(1))}';
    }

    final perMatch = RegExp(
      r'^per\s+(.+)$',
      caseSensitive: false,
    ).firstMatch(trimmed);
    if (perMatch != null) {
      return '${t("per")} ${tDynamic(perMatch.group(1)!)}';
    }

    final quantityLeftMatch = RegExp(
      r'^(.+?)\s+([A-Za-z ]+)\s+left$',
      caseSensitive: false,
    ).firstMatch(trimmed);
    if (quantityLeftMatch != null) {
      final amount = quantityLeftMatch.group(1)!.trim();
      final unit = tDynamic(quantityLeftMatch.group(2)!.trim());
      return '$amount $unit ${t("left")}';
    }

    final unitLeftMatch = RegExp(
      r'^([A-Za-z ]+)\s+left$',
      caseSensitive: false,
    ).firstMatch(trimmed);
    if (unitLeftMatch != null) {
      final unit = tDynamic(unitLeftMatch.group(1)!.trim());
      return '$unit ${t("left")}';
    }

    final key = _dynamicKey(trimmed);
    final translated = t(key);
    return translated == key ? value : translated;
  }

  String _dynamicKey(String value) {
    return value
        .toLowerCase()
        .replaceAll(RegExp(r'[^a-z0-9]+'), '_')
        .replaceAll(RegExp(r'^_+|_+$'), '');
  }
